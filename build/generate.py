#!/usr/bin/env python3
"""Render the marketing pages from build/content.py.

    python3 build/generate.py

Writes index.html (English, site root), <code>/index.html for every other locale,
plus sitemap.xml and robots.txt. Generated files carry a "do not edit" banner —
change build/content.py and re-run instead.

Why generate rather than hand-write 11 pages: the copy has to stay in step across
locales, and hreflang only works if every page links to every other one. Both are
mechanical and both rot the moment they are maintained by hand.

Kept deliberately dependency-free (no Jinja, no npm) so it runs anywhere and so
Vercel needs no build step — the output is committed.
"""
import html
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).parent))
from content import CONTACT, DELETION, LOCALES, SITE  # noqa: E402

ROOT = pathlib.Path(__file__).parent.parent

BANNER = ("<!-- Generated by build/generate.py from build/content.py — do not edit "
          "by hand; your changes will be overwritten. -->")

# Tab icon. Without these the site had no favicon at all, so browsers fell back to
# a blank page glyph (and a 404 on /favicon.ico) — the tab, the bookmark and the
# history entry all showed a generic document next to the TribeSentry name.
#
# The images come from the app's own AppIcon, so a bookmark looks like the app it
# belongs to. Root-relative like every other asset here, because the localised
# pages live one directory down.
#
# Both an .ico and a .png: the .ico carries 16/32/48 so each context is rendered
# from a size drawn for it rather than downscaled from one big bitmap, and the
# apple-touch-icon is what iOS uses for a home-screen bookmark. The same three
# lines are duplicated in the hand-written privacy.html and auth-callback.html,
# which this generator does not own.
FAVICONS = '\n'.join([
    '<link rel="icon" href="/favicon.ico" sizes="any">',
    '<link rel="icon" type="image/png" sizes="32x32" href="/favicon-32.png">',
    '<link rel="apple-touch-icon" href="/apple-touch-icon.png">',
])


def e(text: str) -> str:
    """Escape for HTML text content."""
    return html.escape(text, quote=False)


# No trailing slash on locale paths. vercel.json sets trailingSlash: false, so the
# host 308-redirects /ar/ to /ar — and a canonical or hreflang pointing at a redirect
# is a canonical pointing at the wrong URL. Emit the address that actually returns
# 200. Verified against a real deployment, not assumed.
def url_for(code: str) -> str:
    return f"{SITE}/" if code == "" else f"{SITE}/{code}"


def rel(target: str) -> str:
    """Link to the page for `target`. Root-relative throughout, so the same string
    is valid from the root page and from a locale subdirectory alike."""
    return "/" if target == "" else f"/{target}"


def asset(name: str) -> str:
    """Root-relative asset paths: the localised pages live one level down."""
    return f"/{name}"


# og:locale wants language_TERRITORY; a bare "en" is not a valid value. Only the
# territory is a guess, and it is used for nothing but social-card metadata.
OG_TERRITORY = {
    "en": "en_US", "de": "de_DE", "es": "es_ES", "fr": "fr_FR", "pt-BR": "pt_BR",
    "ru": "ru_RU", "hi": "hi_IN", "ar": "ar_AR", "he": "he_IL", "ja": "ja_JP",
    "zh-Hans": "zh_CN",
}


def lang_menu(current: str, loc: dict) -> str:
    items = "\n".join(
        f'        <a href="{rel(other["code"])}" hreflang="{other["hreflang"]}"'
        f'{" aria-current=\"true\"" if other["code"] == current else ""}>{e(other["name"])}</a>'
        for other in LOCALES
    )
    label = next(l["name"] for l in LOCALES if l["code"] == current)
    return (
        f'      <details class="langs">\n'
        f'        <summary aria-label="{e(loc["lang_label"])}">{e(label)} ▾</summary>\n'
        f'        <div class="menu">\n{items}\n        </div>\n'
        f'      </details>'
    )


def hreflangs(current: str) -> str:
    lines = [
        f'<link rel="alternate" hreflang="{l["hreflang"]}" href="{url_for(l["code"])}">'
        for l in LOCALES
    ]
    lines.append(f'<link rel="alternate" hreflang="x-default" href="{url_for("")}">')
    lines.append(f'<link rel="canonical" href="{url_for(current)}">')
    return "\n".join(lines)


def render(loc: dict) -> str:
    code = loc["code"]
    privacy_href = "/privacy"

    pillars = "\n".join(
        f'''    <div class="pillar">
      <span class="icon" aria-hidden="true">{icon}</span>
      <h3>{e(title)}</h3>
      <p>{e(body)}</p>
    </div>''' for icon, title, body in loc["pillars"]
    )

    features = "\n".join(
        f'''      <div class="feature">
        <h4>{e(title)}</h4>
        <p>{e(body)}</p>
      </div>''' for title, body in loc["features"]
    )

    bullets = "\n".join(
        f"        <li><strong>{e(lead)}</strong> {e(rest)}</li>"
        for lead, rest in loc["privacy_bullets"]
    )

    tail = e(loc["privacy_tail"]).replace(
        "{link}", f'<a href="{privacy_href}">{e(loc["privacy_link"])}</a>'
    )

    free_items = "\n".join(f"          <li>{e(i)}</li>" for i in loc["free_items"])

    return f'''<!doctype html>
<html lang="{loc["lang"]}" dir="{loc["dir"]}">
<head>
{BANNER}
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{e(loc["title"])}</title>
<meta name="description" content="{html.escape(loc["desc"])}">
<meta property="og:title" content="{html.escape(loc["title"])}">
<meta property="og:description" content="{html.escape(loc["desc"])}">
<meta property="og:type" content="website">
<meta property="og:url" content="{url_for(code)}">
<meta property="og:locale" content="{OG_TERRITORY[loc["lang"]]}">
{hreflangs(code)}
{FAVICONS}
<link rel="stylesheet" href="{asset("style.css")}">
</head>
<body>

<header class="site">
  <div class="wrap">
    <a class="logo" href="{rel("")}">Tribe<span>Sentry</span></a>
    <nav>
      <a href="#features">{e(loc["nav"][0])}</a>
      <a href="#privacy">{e(loc["nav"][1])}</a>
      <a href="#pricing">{e(loc["nav"][2])}</a>
{lang_menu(code, loc)}
    </nav>
  </div>
</header>

<div class="wrap">
  <div class="hero">
    <h1>{e(loc["hero_h1"])}</h1>
    <p class="lede">{e(loc["hero_lede"])}</p>
    <div class="cta">
      <!-- TODO: replace with the real Play listing URL once the app is live. -->
      <a class="btn btn-primary" href="#pricing">{e(loc["cta1"])}</a>
      <a class="btn btn-secondary" href="#privacy">{e(loc["cta2"])}</a>
    </div>
    <p class="note">{e(loc["note"])}</p>
  </div>

  <div class="pillars">
{pillars}
  </div>
</div>

<section id="features">
  <div class="wrap">
    <h2>{e(loc["features_h2"])}</h2>
    <p class="sub">{e(loc["features_sub"])}</p>
    <div class="features">
{features}
    </div>
  </div>
</section>

<section id="privacy">
  <div class="wrap">
    <h2>{e(loc["privacy_h2"])}</h2>
    <p class="sub">{e(loc["privacy_sub"])}</p>
    <div class="privacy-callout">
      <strong>{e(loc["privacy_lead"])}</strong>
      <ul>
{bullets}
      </ul>
    </div>
    <p class="privacy-tail">{tail}</p>
  </div>
</section>

<section id="pricing">
  <div class="wrap">
    <h2>{e(loc["pricing_h2"])}</h2>
    <p class="sub">{e(loc["pricing_sub"])}</p>
    <div class="plans">
      <div class="plan featured">
        <h3>{e(loc["free_name"])}</h3>
        <div class="price">{e(loc["free_price"])}</div>
        <ul>
{free_items}
        </ul>
      </div>
    </div>
  </div>
</section>

<footer class="site">
  <div class="wrap">
    <div class="links">
      <a href="{privacy_href}">{e(loc["footer_privacy"])}</a>
      <a href="{deletion_path(code)}">{e(DELETION[code]["h1"])}</a>
      <a href="mailto:{CONTACT}">{e(loc["footer_contact"])}</a>
    </div>
    <div>&copy; TribeSentry — smart-apps</div>
    <p class="disclaimer">{e(loc["disclaimer"])}</p>
  </div>
</footer>

</body>
</html>
'''


def deletion_path(code: str) -> str:
    """Site-absolute path. Not rel(code) + "delete-account" — rel returns "/de" with
    no trailing slash, so concatenating gives "/dedelete-account"."""
    return "/delete-account" if code == "" else f"/{code}/delete-account"


def deletion_url(code: str) -> str:
    return f"{SITE}{deletion_path(code)}"


def render_deletion(loc: dict) -> str:
    """The account-deletion page Play requires at a public URL.

    Deliberately plain: no hero, no pricing, no call to action. Someone reaching this
    page wants to leave, and a marketing pitch in the way is both obnoxious and the
    kind of thing a policy reviewer flags as an obstruction.
    """
    code = loc["code"]
    d = DELETION[code]

    steps = "\n".join(f"        <li>{e(s)}</li>" for s in d["steps"])
    removed = "\n".join(f"        <li>{e(r)}</li>" for r in d["removed"])
    email = e(d["email"]).replace(
        "{contact}", f'<a href="mailto:{CONTACT}">{CONTACT}</a>'
    )

    alts = "\n".join(
        f'<link rel="alternate" hreflang="{o["hreflang"]}" href="{deletion_url(o["code"])}">'
        for o in LOCALES
    )

    return f'''<!doctype html>
<html lang="{loc["lang"]}" dir="{loc["dir"]}">
<head>
{BANNER}
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{e(d["title"])}</title>
<meta name="description" content="{html.escape(d["desc"])}">
{alts}
<link rel="alternate" hreflang="x-default" href="{deletion_url("")}">
<link rel="canonical" href="{deletion_url(code)}">
{FAVICONS}
<link rel="stylesheet" href="{asset("style.css")}">
</head>
<body>

<header class="site">
  <div class="wrap">
    <a class="logo" href="{rel(code)}">Tribe<span>Sentry</span></a>
  </div>
</header>

<div class="wrap doc">
  <h1>{e(d["h1"])}</h1>
  <p class="lede-sm">{e(d["intro"])}</p>

  <h2>{e(d["steps_h2"])}</h2>
  <ol>
{steps}
  </ol>

  <h2>{e(d["removed_h2"])}</h2>
  <ul>
{removed}
  </ul>

  <h2>{e(d["kept_h2"])}</h2>
  <p>{e(d["kept"])}</p>

  <h2>{e(d["email_h2"])}</h2>
  <p>{email}</p>

  <h2>{e(d["retention_h2"])}</h2>
  <p>{e(d["retention"])}</p>

  <p class="doc-back"><a href="{rel(code)}">&larr; {e(d["back"])}</a></p>
</div>

</body>
</html>
'''


def sitemap() -> str:
    """Every locale as one <url> carrying the full alternate set, which is what
    Search Console expects for a multilingual site."""
    entries = []
    for loc in LOCALES:
        alts = "\n".join(
            f'      <xhtml:link rel="alternate" hreflang="{o["hreflang"]}" href="{url_for(o["code"])}"/>'
            for o in LOCALES
        )
        entries.append(
            f'''  <url>
    <loc>{url_for(loc["code"])}</loc>
{alts}
      <xhtml:link rel="alternate" hreflang="x-default" href="{url_for("")}"/>
  </url>'''
        )
    entries.append(f'  <url>\n    <loc>{SITE}/privacy</loc>\n  </url>')
    # English only, like /privacy: Apple and Play each want one reachable support
    # URL, and support copy nobody has reviewed in ten languages would be worse than
    # none at all. Add locales here if that ever changes.
    entries.append(f'  <url>\n    <loc>{SITE}/support</loc>\n  </url>')
    for loc in LOCALES:
        entries.append(f'  <url>\n    <loc>{deletion_url(loc["code"])}</loc>\n  </url>')
    body = "\n".join(entries)
    return f'''<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9"
        xmlns:xhtml="http://www.w3.org/1999/xhtml">
{body}
</urlset>
'''


def robots() -> str:
    return f'''User-agent: *
Allow: /

# The password-reset landing page. Nothing to index, and it should never surface
# in a search result where someone might mistake it for a sign-in page.
Disallow: /auth-callback.html

Sitemap: {SITE}/sitemap.xml
'''


def main() -> int:
    written = []
    for loc in LOCALES:
        out = ROOT / "index.html" if loc["code"] == "" else ROOT / loc["code"] / "index.html"
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(render(loc), encoding="utf-8")
        written.append(out.relative_to(ROOT))

        # Written as <code>/delete-account.html and routed to the extensionless
        # /delete-account by vercel.json, matching how /privacy is served.
        name = "delete-account.html"
        doc = ROOT / name if loc["code"] == "" else ROOT / loc["code"] / name
        doc.write_text(render_deletion(loc), encoding="utf-8")
        written.append(doc.relative_to(ROOT))

    (ROOT / "sitemap.xml").write_text(sitemap(), encoding="utf-8")
    (ROOT / "robots.txt").write_text(robots(), encoding="utf-8")
    written += [pathlib.Path("sitemap.xml"), pathlib.Path("robots.txt")]

    for p in written:
        print(f"wrote {p}")
    print(f"\n{len(LOCALES)} locale(s)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
