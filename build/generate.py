#!/usr/bin/env python3
"""Render the marketing pages from build/content.py.

    python3 build/generate.py

Writes index.html (English, site root), <code>/index.html for every other locale,
plus sitemap.xml and robots.txt. Generated files carry a "do not edit" banner —
change build/content.py and re-run instead.

Why generate rather than hand-write 11 pages: the copy has to stay in step across
locales, and hreflang only works if every page links to every other one. Both are
mechanical and both rot the moment they are maintained by hand.

Kept deliberately dependency-free (no Jinja, no npm) so it runs anywhere and so
Vercel needs no build step — the output is committed.
"""
import html
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).parent))
from content import CONTACT, DELETION, LOCALES, SITE  # noqa: E402

ROOT = pathlib.Path(__file__).parent.parent

BANNER = ("<!-- Generated by build/generate.py from build/content.py — do not edit "
          "by hand; your changes will be overwritten. -->")

# Tab icon. Without these the site had no favicon at all, so browsers fell back to
# a blank page glyph (and a 404 on /favicon.ico) — the tab, the bookmark and the
# history entry all showed a generic document next to the TribeSentry name.
#
# The images come from the app's own AppIcon, so a bookmark looks like the app it
# belongs to. Root-relative like every other asset here, because the localised
# pages live one directory down.
#
# Both an .ico and a .png: the .ico carries 16/32/48 so each context is rendered
# from a size drawn for it rather than downscaled from one big bitmap, and the
# apple-touch-icon is what iOS uses for a home-screen bookmark. The same three
# lines are duplicated in the hand-written privacy.html and auth-callback.html,
# which this generator does not own.
FAVICONS = '\n'.join([
    '<link rel="icon" href="/favicon.ico" sizes="any">',
    '<link rel="icon" type="image/png" sizes="32x32" href="/favicon-32.png">',
    '<link rel="apple-touch-icon" href="/apple-touch-icon.png">',
])

# One card for every locale. The wordmark and the tagline on it are English, which is
# the trade for a single 1200x630 file: a link shared anywhere renders as the product
# instead of as a grey rectangle. Regenerate it with marketer's tools/og_card.py.
OG_IMAGE = '\n'.join([
    f'<meta property="og:image" content="{SITE}/og.png">',
    '<meta property="og:image:width" content="1200">',
    '<meta property="og:image:height" content="630">',
    '<meta name="twitter:card" content="summary_large_image">',
])


# The three pillars are the same three concepts, in the same order, in every
# locale — offline, crash detection, privacy — so the icon is positional and the
# emoji in content.py is ignored. Line-art SVG rather than emoji: emoji render as
# a different picture on every platform (and as full-colour cartoons on Apple),
# which is the single most casual-looking thing on an otherwise restrained page.
# currentColor so they inherit the accent, and aria-hidden because the heading
# beside each one already says what it is.
PILLAR_ICONS = [
    # offline map — a folded map with a signal slash
    '<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.6" '
    'stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">'
    '<path d="M9 4 3 6.5v13L9 17l6 2.5 6-2.5v-13L15 6.5Z"/><path d="M9 4v13"/>'
    '<path d="M15 6.5v13"/></svg>',
    # crash detection — a car. An earlier version added an "impact burst" above it
    # and the extra strokes turned the whole thing into an unreadable blob at
    # 24px; rendered side by side, the plain car was the only one that still read
    # as a car. Complexity is the enemy at this size.
    '<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.6" '
    'stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">'
    '<path d="M4 16h16"/><path d="M5.6 16v-3l1.9-4A1.9 1.9 0 0 1 9.2 8h5.6a1.9 1.9 0 0 1 '
    '1.7 1l1.9 4v3"/><circle cx="8.6" cy="16" r="1.6"/><circle cx="15.4" cy="16" r="1.6"/>'
    '</svg>',
    # privacy — a shield, echoing the app icon
    '<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.6" '
    'stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">'
    '<path d="M12 21s7-3.2 7-9V5.6L12 3 5 5.6V12c0 5.8 7 9 7 9Z"/>'
    '<path d="m9 11.8 2.1 2.1L15 10"/></svg>',
]


# The live App Store listing. A constant because the hero CTA on all eleven pages
# points at it, and because the previous placeholder ("#pricing", with a TODO beside
# it) survived three rounds of edits without anyone noticing the button went nowhere.
#
# iOS only, on purpose: there is no public Play listing yet, so no Play button and —
# just as importantly — no locale may claim Android in the note under the CTA.
APP_STORE_URL = "https://apps.apple.com/app/id6798410492"

# Search-intent landing pages. Hand-written English HTML at the repo root, because
# they have nothing to keep in step across locales — the reason the rest of this file
# exists. Named here so the sitemap and the in-page links share one spelling.
LANDING_LIFE360 = "life360-alternative"
LANDING_FREE = "free-family-location-sharing"
LANDING_PAGES = [LANDING_LIFE360, LANDING_FREE]


def e(text: str) -> str:
    """Escape for HTML text content."""
    return html.escape(text, quote=False)


def linked(text: str, href: str, label: str) -> str:
    """Escaped `text` with its {link} placeholder swapped for an anchor. Keeps the
    copy in content.py readable as a sentence instead of splitting it around markup."""
    return e(text).replace("{link}", f'<a href="{href}">{e(label)}</a>')


# No trailing slash on locale paths. vercel.json sets trailingSlash: false, so the
# host 308-redirects /ar/ to /ar — and a canonical or hreflang pointing at a redirect
# is a canonical pointing at the wrong URL. Emit the address that actually returns
# 200. Verified against a real deployment, not assumed.
def url_for(code: str) -> str:
    return f"{SITE}/" if code == "" else f"{SITE}/{code}"


def rel(target: str) -> str:
    """Link to the page for `target`. Root-relative throughout, so the same string
    is valid from the root page and from a locale subdirectory alike."""
    return "/" if target == "" else f"/{target}"


def asset(name: str) -> str:
    """Root-relative asset paths: the localised pages live one level down."""
    return f"/{name}"


# og:locale wants language_TERRITORY; a bare "en" is not a valid value. Only the
# territory is a guess, and it is used for nothing but social-card metadata.
OG_TERRITORY = {
    "en": "en_US", "de": "de_DE", "es": "es_ES", "fr": "fr_FR", "pt-BR": "pt_BR",
    "ru": "ru_RU", "hi": "hi_IN", "ar": "ar_AR", "he": "he_IL", "ja": "ja_JP",
    "zh-Hans": "zh_CN",
}


def lang_menu(current: str, loc: dict) -> str:
    items = "\n".join(
        f'        <a href="{rel(other["code"])}" hreflang="{other["hreflang"]}"'
        f'{" aria-current=\"true\"" if other["code"] == current else ""}>{e(other["name"])}</a>'
        for other in LOCALES
    )
    label = next(l["name"] for l in LOCALES if l["code"] == current)
    return (
        f'      <details class="langs">\n'
        f'        <summary aria-label="{e(loc["lang_label"])}">{e(label)} ▾</summary>\n'
        f'        <div class="menu">\n{items}\n        </div>\n'
        f'      </details>'
    )


def hreflangs(current: str) -> str:
    lines = [
        f'<link rel="alternate" hreflang="{l["hreflang"]}" href="{url_for(l["code"])}">'
        for l in LOCALES
    ]
    lines.append(f'<link rel="alternate" hreflang="x-default" href="{url_for("")}">')
    lines.append(f'<link rel="canonical" href="{url_for(current)}">')
    return "\n".join(lines)


def render_compare(loc: dict) -> str:
    """The Life360 comparison table.

    Its own function because it is the one section with real internal structure — a
    scroll container, a table, and per-cell classes that carry meaning — and inlining
    all of that in the page template buried the surrounding copy.

    The header row is not translated: the first cell is a spacer and the other two are
    brand names, which read the same in every locale.
    """
    cells = []
    for label, ours, theirs, their_class in loc["compare_rows"]:
        attr = f' class="{their_class}"' if their_class else ""
        cells.append(
            f'          <tr>\n'
            f'            <td>{e(label)}</td>\n'
            f'            <td class="yes">{e(ours)}</td>\n'
            f'            <td{attr}>{e(theirs)}</td>\n'
            f'          </tr>'
        )
    rows = "\n".join(cells)

    # Only English has a long-form comparison to link to — the landing pages are not
    # translated — so every other locale ends on the note.
    more = ""
    if loc.get("compare_more"):
        anchor = linked(loc["compare_more"], f"/{LANDING_LIFE360}", loc["compare_more_link"])
        more = f'\n    <p class="sub">{anchor}</p>'

    return f'''<section id="compare" class="reveal">
  <div class="wrap">
    <h2>{e(loc["compare_h2"])}</h2>
    <p class="sub">{e(loc["compare_sub"])}</p>
    <div class="compare-scroll">
      <table class="compare">
        <thead>
          <tr><th>&nbsp;</th><th>TribeSentry</th><th>Life360</th></tr>
        </thead>
        <tbody>
{rows}
        </tbody>
      </table>
    </div>{more}
    <p class="compare-note">{e(loc["compare_note"])}</p>
  </div>
</section>'''


def render(loc: dict) -> str:
    code = loc["code"]
    privacy_href = "/privacy"

    pillars = "\n".join(
        f'''    <div class="pillar">
      <span class="icon" aria-hidden="true">{PILLAR_ICONS[i]}</span>
      <h3>{e(title)}</h3>
      <p>{e(body)}</p>
    </div>''' for i, (_emoji, title, body) in enumerate(loc["pillars"])
    )

    features = "\n".join(
        f'''      <div class="feature">
        <h4>{e(title)}</h4>
        <p>{e(body)}</p>
      </div>''' for title, body in loc["features"]
    )

    bullets = "\n".join(
        f"        <li><strong>{e(lead)}</strong> {e(rest)}</li>"
        for lead, rest in loc["privacy_bullets"]
    )

    tail = e(loc["privacy_tail"]).replace(
        "{link}", f'<a href="{privacy_href}">{e(loc["privacy_link"])}</a>'
    )

    # Only English links out of the pricing note, for the same reason as compare_more.
    plus_note = (linked(loc["plus_note"], f"/{LANDING_FREE}", loc["plus_note_link"])
                 if loc.get("plus_note_link") else e(loc["plus_note"]))

    free_items = "\n".join(f"          <li>{e(i)}</li>" for i in loc["free_items"])
    plus_items = "\n".join(f"          <li>{e(i)}</li>" for i in loc["plus_items"])

